# 优先级（先匹配到的生效）
FRANCHISE_ORDER = ["竞速", "格斗", "射击", "恐怖", "角色扮演", "策略", "模拟", "解谜", "冒险", "独立", "动作"]


def classify_name(name: str) -> str:
    n = name
    for cat in FRANCHISE_ORDER:
        for kw in FRANCHISE[cat]:
            if kw in n:
                return cat
    # 兜底：关键词字典（来自 scraper.CATEGORY_KW，但顺序调整）
    for cat, kws in S.CATEGORY_KW.items():
        for kw in kws:
            if kw.lower() in n.lower():
                return cat
    return "其他"


def main():
    path = "public/game-resources.json"
    data = json.load(open(path, encoding="utf-8"))
    res = data["resources"]
    changed = 0
    for g in res:
        genre = classify_name(g.get("name", ""))
        if g.get("category") != genre:
            changed += 1
        g["category"] = genre
        # tags 仅写入真实分类（其他不写，保持与原始设计一致）
        g["tags"] = [genre] if genre != "其他" else []
    json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    json.dump(data, open("game-resources.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    from collections import Counter
    c = Counter(g["category"] for g in res)
    print(f"已重新分类 {len(res)} 款（变更 {changed} 款）:")
    for k, v in c.most_common():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
